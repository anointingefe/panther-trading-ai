from __future__ import annotations

from typing import Any


DEMO_EVIDENCE_MODES = frozenset({"demo", "contest", "paper", "simulated"})


def classify_imported_evidence(source: Any, comment: Any) -> str:
    """Classify imported broker history without trusting an unverified MT5 record.

    Panther's demo runner stamps its orders with a demo-specific comment and the
    live runner stamps live orders separately. Legacy/foreign MT5 history that
    cannot be identified is intentionally marked unknown and excluded from demo
    readiness evidence.
    """
    normalized_source = str(source or "").strip().lower()
    normalized_comment = str(comment or "").strip().lower()

    if normalized_source in {"paper", "simulated", "demo", "contest"}:
        return normalized_source
    if normalized_source == "mt5":
        if "panther demo" in normalized_comment or "demo incubation" in normalized_comment:
            return "demo"
        if "panther live" in normalized_comment or "live auto" in normalized_comment:
            return "live"
        return "unknown"
    return "unknown"


def position_evidence_mode(position: dict[str, Any]) -> str:
    metadata = position.get("metadata") or {}
    explicit = str(metadata.get("evidence_mode") or "").strip().lower()
    if explicit:
        return explicit

    source = str(metadata.get("source") or "").strip().lower()
    if source:
        return classify_imported_evidence(source, metadata.get("comment"))

    # Legacy local PaperPositionBook records pre-date evidence tagging. They are
    # generated by Panther's paper path, so they remain valid demo evidence.
    return "paper"


def is_demo_evidence(position: dict[str, Any]) -> bool:
    return position_evidence_mode(position) in DEMO_EVIDENCE_MODES
